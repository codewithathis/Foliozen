import { orderedSections, sectionHasContent, SECTION_HEADINGS, type Resume } from "@/lib/schema";
import { bulletsEnv, contactParts, href, month, range, README, tex, type LatexOutput } from "./common";

/**
 * "Modern" style: sans-serif name and headline, company-first entries,
 * rule under section titles, skills in two columns.
 */
export function renderModern(r: Resume): LatexOutput {
  const paper = r.meta.paper === "a4" ? "a4paper" : "letterpaper";
  const body = orderedSections(r)
    .filter((s) => sectionHasContent(r, s))
    .map((s) => section(s, r))
    .join("\n");

  const texSrc = `%% Resume, "Modern" style, generated by Foliozen
%% Compile with pdflatex.
\\documentclass[${paper},11pt]{article}

\\usepackage[margin=0.55in,top=0.45in,bottom=0.5in]{geometry}
\\usepackage[T1]{fontenc}
\\usepackage[utf8]{inputenc}
\\usepackage[default]{sourcesanspro}
\\usepackage{xcolor}
\\usepackage{titlesec}
\\usepackage{enumitem}
\\usepackage{tabularx}
\\usepackage{microtype}
\\usepackage[hidelinks]{hyperref}
\\input{glyphtounicode}
\\pdfgentounicode=1

\\pagestyle{empty}
\\setlength{\\parindent}{0pt}
\\setlength{\\tabcolsep}{0pt}
\\raggedbottom
\\urlstyle{same}

\\titleformat{\\section}
  {\\large\\bfseries}{}{0em}{}[\\titlerule\\vspace{-6pt}]
\\titlespacing*{\\section}{0pt}{10pt}{6pt}

\\newcommand{\\vEntry}[4]{%
  \\item
  \\begin{tabular*}{0.97\\textwidth}{l@{\\extracolsep{\\fill}}r}
    \\textbf{#1} & #2 \\\\
    \\textit{\\small#3} & \\textit{\\small #4} \\\\
  \\end{tabular*}\\vspace{-6pt}}
\\newcommand{\\vEntryOne}[2]{%
  \\item
  \\begin{tabular*}{0.97\\textwidth}{l@{\\extracolsep{\\fill}}r}
    \\textbf{#1} & #2 \\\\
  \\end{tabular*}\\vspace{-6pt}}
\\newenvironment{vEntries}{\\begin{itemize}[leftmargin=*]}{\\end{itemize}}
\\newenvironment{vBullets}{\\begin{itemize}[leftmargin=1.1em,itemsep=1pt,topsep=2pt]}{\\end{itemize}\\vspace{-6pt}}

\\begin{document}

% ---- header ----
\\begin{center}
  {\\Huge\\bfseries ${tex(r.contact.fullName)}}\\\\[4pt]
  ${r.contact.headline ? `{\\itshape\\large ${tex(r.contact.headline)}}\\\\[2pt]` : ""}
  {\\small ${contactParts(r).join(" \\hspace{8pt} ")}}
\\end{center}

${body}
\\end{document}
`;

  return { files: { "resume.tex": texSrc, "README.md": README("Modern", "pdflatex") }, main: "resume.tex", engine: "pdflatex" };
}

function section(id: ReturnType<typeof orderedSections>[number], r: Resume): string {
  const H = `\\section{${SECTION_HEADINGS[id]}}\n`;
  switch (id) {
    case "summary":
      return `${H}\\noindent ${tex(r.summary)}\\par\\vspace{2pt}\n`;
    case "experience":
      return (
        H +
        "\\begin{vEntries}\n" +
        r.experience
          .map(
            (e) =>
              // Company first, then title — matches the engineering layout this style targets.
              `  \\vEntry{${tex(e.company)}}{${range(e.start, e.end, e.current)}}{${tex(e.title)}}{${tex(e.location)}}\n` +
              bulletsEnv(e.bullets, "vBullets"),
          )
          .join("") +
        "\\end{vEntries}\n"
      );
    case "education":
      return (
        H +
        "\\begin{vEntries}\n" +
        r.education
          .map((e) => {
            const deg = [e.degree, e.field].filter(Boolean).join(" in ") + (e.gpa ? `, GPA ${e.gpa}` : "");
            return `  \\vEntry{${tex(e.school)}}{${range(e.start, e.end)}}{${tex(deg)}}{${tex(e.location)}}\n` + bulletsEnv(e.details, "vBullets");
          })
          .join("") +
        "\\end{vEntries}\n"
      );
    case "skills": {
      // Two-column via tabularx (in the in-browser TeX bundle). Avoid multicol —
      // it is not packed into public/tex, so Modern would fail to compile locally.
      const groups = r.skills
        .filter((g) => g.items.length)
        .map((g) => `${g.category ? `\\textbf{${tex(g.category)}:} ` : ""}${tex(g.items.join(", "))}`);
      if (!groups.length) return "";
      const rows: string[] = [];
      for (let i = 0; i < groups.length; i += 2) {
        rows.push(`  ${groups[i]} & ${groups[i + 1] ?? ""} \\\\`);
      }
      return (
        H +
        "\\begin{tabularx}{\\textwidth}{@{}X@{\\hspace{1.2em}}X@{}}\n" +
        rows.join("\n") +
        "\n\\end{tabularx}\\par\\vspace{4pt}\n"
      );
    }
    case "projects":
      return (
        H +
        "\\begin{vEntries}\n" +
        r.projects
          .map((p) => {
            const dates = range(p.start, p.end);
            const link = p.link ? href(p.link) : "";
            return `  \\vEntry{${tex(p.name)}}{${dates || link}}{${tex(p.tech)}}{${dates ? link : ""}}\n` + bulletsEnv(p.bullets, "vBullets");
          })
          .join("") +
        "\\end{vEntries}\n"
      );
    case "certifications":
      return (
        H +
        "\\begin{vEntries}\n" +
        r.certifications
          .map((c) => {
            const left = `${tex(c.name)}${c.issuer ? ` --- ${tex(c.issuer)}` : ""}`;
            return `  \\vEntryOne{${left}}{${month(c.date)}}\n`;
          })
          .join("") +
        "\\end{vEntries}\n"
      );
  }
}
